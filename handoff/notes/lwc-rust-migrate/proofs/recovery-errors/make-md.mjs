// Builds ../recovery-errors.md from compare.json (fixtures + extras) and usage/{shipped,rust}.json.
import fs from 'fs';
const J = (p) => JSON.parse(fs.readFileSync(new URL(p, import.meta.url), 'utf8'));
const cmp = J('./compare.json');
const fmt = (e) => (e.location ? `${e.code}@${e.location.line}:${e.location.column} s${e.location.start}/l${e.location.length}` : `${e.code}@-`);
const list = (x) => x == null ? '—' : x === 'NO ERROR' ? 'NO ERROR' : x.errors ? x.errors.map(fmt).join(', ') : `**${x.name ?? ''}** ${fmt(x)} ${x.message ? '`' + x.message.split('\n')[0].slice(0, 90).replace(/\|/g, '\\|') + '`' : ''}`;
let md = `# Recovery-mode errors[]: shipped 9.5.3 vs Rust lwc-js

Generated by \`proofs/recovery-errors/make-md.mjs\` (generated ${new Date().toISOString()}). The inputs are the 12
babel-plugin-component \`error-recovery-mode\` fixtures plus extras. Harness opts: \`namespace: 'lwc', name: 'test',
filename: 'test.js', enablePrivateMethods: true, experimentalErrorRecoveryMode: true\`, plus \`dynamicImports\` for the
dynamic-import fixture.

Each entry is \`code@line:col s<start>/l<length>\`. Messages are compared verbatim too (see compare.json).

**Rule:** drop shipped's duplicate LWC1096 entries (the @api get/set pair reported twice) and the case where shipped
crashes on 1212. Everything else must be identical in order and content.

## Fixtures and extras (shipped AggregateError.errors[] vs Rust diagnostics[])

| case | verdict | shipped | Rust |
|---|---|---|---|
`;
for (const c of cmp) md += `| ${c.k} | ${c.verdict} | ${list(c.s)} | ${list(c.r)} |\n`;
const us = J('./usage/shipped.json'), ur = J('./usage/rust.json');
const norm = (x) => JSON.parse(JSON.stringify(x).split(process.cwd() + '/usage/test.js').join('test.js').split('/workspace/notes/lwc-rust-migrate/proofs/recovery-errors/usage/test.js').join('test.js'));
md += `
## Decorator-import usage probes (LWC1103/1104), non-recovery and [rec]

Shipped's validateImportedLwcDecoratorUsage was ported in this round (scope-resolved references, specifier order,
Babel parent/grandparent locations). Messages are compared after normalizing shipped's cwd-resolved \`test.js\` path.

| case | verdict | shipped | Rust |
|---|---|---|---|
`;
for (const k of Object.keys(us)) {
  const s = norm(us[k]), r = ur[k];
  const same = JSON.stringify(s) === JSON.stringify(r);
  const crash = s && s.code && (s.code === 1007 || s.code === 1198) && /TypeError|not enabled/.test(s.message || '');
  md += `| ${k} | ${same ? 'IDENTICAL' : crash ? 'SHIPPED CRASH (accepted)' : '**MISMATCH**'} | ${list(s)} | ${list(r)} |\n`;
}
md += `
## Accepted divergences (each a shipped crash or a duplicate; see decisions.tsv)

- **extra/1212-decorated-private-method**: shipped throws \`TypeError\` LWC1007 out of recovery mode. Rust reports aggregate [LWC1212 at 3:2].
- **Duplicate LWC1096 for an @api get/set pair (multi-error \`g\`)**: shipped lists it twice. Rust lists it once. All other entries are identical in order and content.
  (The fixture api/duplicate-api-property duplicates come from two real duplicate fields, and Rust reproduces them.)
- **aliased** (\`import { api as A }\`): shipped crashes with TypeError LWC1007 (\`getBinding('api')\` is undefined). Rust validates through the alias.
- **class-decorator / class-expr-decorator / member-decorator [rec]**: shipped's Babel re-parse throws LWC1198 "Decorators are not enabled". Rust reports the LWC errors. In non-recovery mode, both are identical.
- **private-api / private-wire / private-two [rec]**: shipped crashes with TypeError LWC1007 (\`startsWith\` / "Property name expected type of string"). Rust reports [1103, 1101, …]. private-prop (@track only), which does not crash, is identical.

## Seam differences outside lwc-js (not changed; napi/lwc-shared/harness-owned)

- Rust's aggregate \`message\` is the header line plus one line per sub-error. Shipped's is exactly "Multiple errors occurred during compilation.".
- Rust's aggregate \`code\` is the first diagnostic's code. Shipped's is \`null\`.
- napi \`JsCompileError\` has no \`errors[]\` and no \`location.start/length\`, so the harness recovers codes from the message. Exposing \`errors[]\` needs a napi change and harness forwarding.
`;
fs.writeFileSync(new URL('../recovery-errors.md', import.meta.url), md);
console.log(md.split('\n').filter((l) => /MISMATCH/.test(l)).join('\n') || 'no mismatches');
