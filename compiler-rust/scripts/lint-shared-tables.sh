#!/usr/bin/env bash
# AB-0011 (AB-D0002): no copies of @lwc/shared tables/helpers outside crates/lwc-shared.
# Ratchet: every hit line must be listed in scripts/lint-shared-tables.baseline as
# "<file><TAB><trimmed line text>" (no line numbers, so unrelated edits don't churn it; a line hit by
# several rules is one entry). A hit not in the baseline fails (new duplicate). A baseline entry with no hit
# fails too (remove it: the baseline may only shrink). The baseline may never exceed CEILING entries.
#
# Usage: scripts/lint-shared-tables.sh [--self-test] [<repo-root>]   (works from any cwd)
# Exit: 0 pass; 1 lint failure; 2 usage/self-test failure.
set -euo pipefail

CEILING=23
SELF_TEST=0
ROOT=""
for a in "$@"; do
  case "$a" in
    --self-test) SELF_TEST=1 ;;
    -h|--help) sed -n '2,8p' "$0"; exit 0 ;;
    -*) echo "unknown option: $a" >&2; exit 2 ;;
    *) ROOT="$a" ;;
  esac
done
[ -n "$ROOT" ] || ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ROOT="$(cd "$ROOT" && pwd)"
BASELINE="$ROOT/scripts/lint-shared-tables.baseline"
command -v rg >/dev/null || { echo "lint-shared-tables: rg (ripgrep) is required" >&2; exit 2; }

# id <TAB> lwc_shared module <TAB> regex <TAB> extra allowed path glob ("-" = none)
RULES=$(cat <<'R'
L1	lwc_shared::void_elements	\b(const|static)\s+VOID\w*\s*:	-
L2	lwc_shared::html_attributes	\bfn\s+is_boolean_attribute\b	-
L3	lwc_shared::custom_element	\bfn\s+generate_custom_element_tag_name\b	-
L4	lwc_shared::{void_elements,html_attributes,aria}	\bfn\s+(is_void(_element)?|is_global_html_attribute|is_aria_attribute|kebab_case_to_camel_case|is_id_referencing\w*)\b	-
L5	lwc_shared::{aria,html_attributes,namespaces}	\b(const|static)\s+(ARIA_\w+|GLOBAL_ATTRIBUTE\w*|SPECIAL_\w*ATTR\w*|BOOLEAN_ATTRIBUTES|AMBIGUOUS_PROP_SET|DISALLOWED_PROP_SET|ID_REFERENCING\w*|\w*_(NS|NAMESPACE))\s*:	-
L6	lwc_template::shared	\bfn\s+(to_property_name|kebabcase_to_camelcase\w*|camel_name)\b	crates/lwc-template/src/shared/
L7	lwc_shared::{aria,namespaces}	"aria-brailleroledescription"|"http://www\.w3\.org/1999/xhtml"	-
S1	lwc_shared::style	\bfn\s+(parse_style_text|split_important|normalize_style_attribute_value)\b	-
R
)

# scan <dir> -> lines "rule<TAB>module<TAB>file<TAB>line<TAB>text" for every hit not allowed
scan() {
  local dir="$1"
  local hits rrc
  while IFS=$'\t' read -r id module re allow; do
    # rg: 0 = hits, 1 = no hit, 2 = error (bad regex, unreadable file, ...): an error must fail the lint, never read as clean.
    rrc=0; hits="$(cd "$dir" && rg -n --no-heading --color never --type rust -g 'crates/*/src/**' -g '!crates/lwc-shared/**' -e "$re" .)" || rrc=$?
    case $rrc in 0) ;; 1) continue;; *) echo "!! lint-shared-tables: rg failed (rc=$rrc) for rule $id" >&2; exit 2;; esac
      while IFS= read -r hit; do
        local file="${hit%%:*}"; file="${file#./}"
        local rest="${hit#*:}"; local line="${rest%%:*}"; local text="${rest#*:}"
        [ "$allow" != "-" ] && [[ "$file" == "$allow"* ]] && continue
        if [ "$id" = L7 ]; then
          grep -q '@generated by tools/gen-shared-tables' <<< "$(head -n1 "$dir/$file")" && continue   # no pipe into grep -q (AB-X0008)
          [[ "$text" =~ //\ lint-shared-tables:\ allow[[:space:]]*$ ]] && continue
        fi
        text="$(printf '%s' "$text" | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//')"
        printf '%s\t%s\t%s\t%s\t%s\n' "$id" "$module" "$file" "$line" "$text"
      done <<<"$hits"
  done <<<"$RULES"
}

if [ "$SELF_TEST" = 1 ]; then
  T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT
  mkdir -p "$T/crates/x/src" "$T/crates/lwc-shared/src" "$T/crates/lwc-template/src/shared"
  # One positive per rule (each tagged "HIT <rule>") and near-misses that must not match.
  cat >"$T/crates/x/src/lib.rs" <<'F'
const VOID: &[&str] = &[]; // HIT L1
fn is_boolean_attribute() {} // HIT L2
fn generate_custom_element_tag_name() {} // HIT L3
fn is_void_element() {} // HIT L4
static HTML_NAMESPACE: &str = ""; // HIT L5
fn camel_name() {} // HIT L6
let a = "aria-brailleroledescription"; // HIT L7
pub fn split_important() {} // HIT S1
fn is_void_elements_x() {}
let v = VOID_ELEMENTS.len();
is_boolean_attribute(a, b);
fn is_boolean_attribute_x() {}
const MY_NSX: u8 = 0;
const DECORATOR_NAMES: [&str; 0] = [];
fn to_property_names() {}
let a = "aria-brailleroledescription"; // lint-shared-tables: allow
let s = split_important(v);
F
  printf '%s\n' 'const VOID: &[&str] = &[];' 'fn camel_name() {}' >"$T/crates/lwc-shared/src/lib.rs"
  printf '%s\n' 'fn to_property_name() {}' >"$T/crates/lwc-template/src/shared/utils.rs"
  printf '%s\n' '// @generated by tools/gen-shared-tables/gen.mjs' 'pub const HTML: &str = "http://www.w3.org/1999/xhtml";' >"$T/crates/x/src/gen.rs"
  got="$(scan "$T" | awk -F'\t' '{print $3":"$4" "$1}' | sort)"
  want="$(grep -n '// HIT ' "$T/crates/x/src/lib.rs" | sed -E 's/^([0-9]+):.*HIT (\w+)$/crates\/x\/src\/lib.rs:\1 \2/' | sort)"
  if [ "$got" != "$want" ] || [ "$(printf '%s\n' "$want" | wc -l)" -ne 8 ]; then
    echo "SELF-TEST FAILED"; echo "--- want"; echo "$want"; echo "--- got"; echo "$got"; exit 2
  fi
  # Ratchet: full baseline passes; a missing entry (new duplicate) or a stale entry fails.
  mkdir -p "$T/scripts"; B="$T/scripts/lint-shared-tables.baseline"
  scan "$T" | awk -F'\t' '{print $3"\t"$5}' | sort -u >"$B"
  "$0" "$T" >/dev/null || { echo "SELF-TEST FAILED: full baseline rejected"; exit 2; }
  sed -i 1d "$B"
  if "$0" "$T" >/dev/null; then echo "SELF-TEST FAILED: unlisted hit accepted"; exit 2; fi
  scan "$T" | awk -F'\t' '{print $3"\t"$5}' | sort -u >"$B"; printf 'crates/x/src/gone.rs\tconst VOID: u8;\n' >>"$B"
  if "$0" "$T" >/dev/null; then echo "SELF-TEST FAILED: stale baseline entry accepted"; exit 2; fi
  # rg error (rc 2, here an unreadable file) must fail the lint (exit 2), not read as "no hit" (AB-0006 rework 2 nit).
  printf 'fn is_boolean_attribute() {}\n' >"$T/crates/x/src/unreadable.rs"; chmod 000 "$T/crates/x/src/unreadable.rs"
  urc=0; "$0" "$T" >/dev/null 2>&1 || urc=$?; chmod 644 "$T/crates/x/src/unreadable.rs"
  [ "$urc" -eq 2 ] || { echo "SELF-TEST FAILED: rg error (unreadable file) gave rc $urc, want 2"; exit 2; }
  echo "lint-shared-tables self-test: ok (8 planted hits detected, near-misses clean, ratchet enforced, rg error -> rc 2)"
  exit 0
fi

[ -f "$BASELINE" ] || { echo "missing baseline $BASELINE" >&2; exit 2; }
HITS="$(scan "$ROOT")"
KEYS="$(printf '%s\n' "$HITS" | awk -F'\t' 'NF{print $3"\t"$5}' | sort -u)"
BASE="$(grep -v '^#' "$BASELINE" | grep -v '^[[:space:]]*$' | sort -u || true)"
nbase=$(printf '%s' "$BASE" | grep -c . || true)
fail=0
if [ "$nbase" -gt "$CEILING" ]; then
  echo "baseline has $nbase entries; the ceiling is $CEILING and may only drop"; fail=1
fi
while IFS=$'\t' read -r id module file line text; do
  [ -n "$id" ] || continue
  if ! grep -qxF "$file"$'\t'"$text" <<<"$BASE"; then
    echo "$file:$line: duplicate of $module ($id); use it"; fail=1
  fi
done <<<"$HITS"
while IFS= read -r b; do
  [ -n "$b" ] || continue
  grep -qxF "$b" <<<"$KEYS" || { echo "stale baseline entry (duplicate removed; delete this line from scripts/lint-shared-tables.baseline): $b"; fail=1; }
done <<<"$BASE"
nhits=$(printf '%s' "$KEYS" | grep -c . || true)
if [ "$fail" = 0 ]; then
  echo "lint-shared-tables: ok ($nhits known duplicate lines, baseline $nbase/$CEILING)"
fi
exit "$fail"
