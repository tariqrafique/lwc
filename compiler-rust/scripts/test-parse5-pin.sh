#!/usr/bin/env bash
# Hermetic self-test for scripts/parse5-pin-check.sh (AB-L0050 condition 3; D-0238 lock source).
# Builds a throwaway parse5 git repo and a one-crate cargo workspace pinning it by rev over a local
# file:// "remote". No [patch], no network; CARGO_HOME in $T. The lock must record the git source.
set -euo pipefail
T="$(mktemp -d /tmp/p5pin-test.XXXXXX)"; trap 'rm -rf "$T"' EXIT
cp "$(cd "$(dirname "$0")" && pwd)/parse5-pin-check.sh" "$T/parse5-pin-check.sh"
S="$T/parse5-pin-check.sh"
export CARGO_HOME="$T/cargo-home"
mkdir -p "$CARGO_HOME"
# Do not set CARGO_NET_OFFLINE: generate-lockfile must fetch the local file://
# bare clone into the scratch CARGO_HOME. The real ~/.cargo is unused.
unset CARGO || true
# shellcheck source=cargo-locked.sh
source "$(cd "$(dirname "$0")" && pwd)/cargo-locked.sh"
fail=0; check() { local name="$1" want="$2"; shift 2; local rc=0; "$@" >"$T/out" 2>&1 || rc=$?
  if [ "$rc" = "$want" ]; then echo "ok   $name -> rc $rc: $(head -1 "$T/out")"; else echo "FAIL $name: want rc $want got $rc: $(tr '\n' ' ' < "$T/out")"; fail=1; fi; }
mkrepo() { local d="$1"; mkdir -p "$d/crates/parse5/src"; git -C "$d" init -q; git -C "$d" config user.email t@t; git -C "$d" config user.name t
  printf '[workspace]\nmembers=["crates/parse5"]\nresolver="2"\n' > "$d/Cargo.toml"
  printf '[package]\nname="parse5"\nversion="0.1.0"\nedition="2021"\n' > "$d/crates/parse5/Cargo.toml"
  echo 'pub fn f() {}' > "$d/crates/parse5/src/lib.rs"; printf 'target/\nignored.rs\n' > "$d/.gitignore"
  git -C "$d" add -A; git -C "$d" commit -qm init; }
P5="$T/p5"; mkrepo "$P5"; rev="$(git -C "$P5" rev-parse HEAD)"
URLREPO="$T/upstream"; git clone -q --bare "$P5" "$URLREPO"
mkroot() { local r="$1" dep="$2"; mkdir -p "$r/crates/lwc-template/src"
  printf '[workspace]\nmembers=["crates/lwc-template"]\nresolver="2"\n' > "$r/Cargo.toml"
  printf '[package]\nname="lwc-template"\nversion="0.1.0"\nedition="2021"\n[dependencies]\n%s\n' "$dep" > "$r/crates/lwc-template/Cargo.toml"
  touch "$r/crates/lwc-template/src/lib.rs"
  local rc=0; (cd "$r" && CARGO_NET_GIT_FETCH_WITH_CLI=true cargo_generate_lockfile >/dev/null 2>"$r/lock.err") || rc=$?
  [ "$rc" = 0 ] || [ "${3:-}" = may-fail ] || { echo "FAIL fixture lock $r: $(tail -2 "$r/lock.err")"; exit 2; }
  if [ -f "$r/Cargo.lock" ]; then mkdir -p "$r/tools/template-diag-diff/driver"; cp "$r/Cargo.lock" "$r/tools/template-diag-diff/driver/Cargo.lock"; fi; }
GIT="parse5 = { git = \"file://$URLREPO\", rev = \"$rev\" }"
mkroot "$T/ok" "$GIT"
check "pinned rev, lock source matches, rev present" 0 env PARSE5_DIR="$P5" "$S" "$T/ok"
mkroot "$T/path" "parse5 = { path = \"$P5/crates/parse5\" }" may-fail
check "path dep after D-0201" 1 env PARSE5_DIR="$P5" "$S" "$T/path"
mkroot "$T/short" "parse5 = { git = \"file://$URLREPO\", rev = \"${rev:0:7}\" }" may-fail
check "short rev" 1 env PARSE5_DIR="$P5" "$S" "$T/short"
zeros="$(printf '0%.0s' {1..40})"
mkroot "$T/absent" "parse5 = { git = \"file://$URLREPO\", rev = \"$zeros\" }" may-fail
E="$T/empty"; mkdir -p "$E"; git -C "$E" init -q; git -C "$E" config user.email t@t; git -C "$E" config user.name t
check "absent rev" 1 env PARSE5_DIR="$E" "$S" "$T/ok"
cp -a "$T/ok" "$T/nosrc"
python3 -c "
import pathlib,sys
p=pathlib.Path(sys.argv[1])
lines=p.read_text().splitlines(True)
out=[]; skip=0; in_pkg=0
for line in lines:
    if line.strip()=='[[package]]':
        in_pkg=0
    if line=='name = \"parse5\"\n':
        in_pkg=1
    if in_pkg and line.startswith('source = '):
        continue
    out.append(line)
p.write_text(''.join(out))
" "$T/nosrc/Cargo.lock"
check "lock missing git source" 1 env PARSE5_DIR="$P5" "$S" "$T/nosrc"
cp -a "$T/ok" "$T/badrev"
python3 -c '
import pathlib,sys
p=pathlib.Path(sys.argv[1]); rev=sys.argv[2]; zeros=sys.argv[3]
t=p.read_text()
t=t.replace("?rev="+rev, "?rev="+zeros, 1)
p.write_text(t)
' "$T/badrev/Cargo.lock" "$rev" "$zeros"
check "lock source rev != Cargo.toml" 1 env PARSE5_DIR="$P5" "$S" "$T/badrev"
cp -a "$T/ok" "$T/drv"
mkdir -p "$T/drv/tools/template-diag-diff/driver"
python3 -c '
import pathlib,sys
src=pathlib.Path(sys.argv[1]).read_text(); zeros=sys.argv[2]
# minimal lock with a parse5 git source whose rev does not match toml
pathlib.Path(sys.argv[3]).write_text("""# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "parse5"
version = "0.1.0"
source = "git+file:///does-not-matter?rev=%s#aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa"
""" % zeros)
' "$T/ok/Cargo.lock" "$zeros" "$T/drv/tools/template-diag-diff/driver/Cargo.lock"
check "driver lock source mismatch" 1 env PARSE5_DIR="$P5" "$S" "$T/drv"
echo '// u' > "$P5/crates/parse5/src/untracked.rs"
check "untracked file does not fail (no longer a path-build gate)" 0 env PARSE5_DIR="$P5" "$S" "$T/ok"
rm "$P5/crates/parse5/src/untracked.rs"
echo '// m' >> "$P5/crates/parse5/src/lib.rs"; git -C "$P5" add -A; git -C "$P5" commit -qam move
check "checkout at other commit is fine if rev exists" 0 env PARSE5_DIR="$P5" "$S" "$T/ok"
O="$T/other"; mkdir -p "$O"; git -C "$O" init -q; git -C "$O" config user.email t@t; git -C "$O" config user.name t
echo x > "$O/README"; git -C "$O" add -A; git -C "$O" commit -qm other
check "rev not in PARSE5_DIR" 1 env PARSE5_DIR="$O" "$S" "$T/ok"
check "no argv is usage" 2 env PARSE5_DIR="$P5" "$S"
check "empty argv is usage" 2 env PARSE5_DIR="$P5" "$S" ""
cp -a "$T/ok" "$T/nodrv"; rm "$T/nodrv/tools/template-diag-diff/driver/Cargo.lock"
check "missing driver lock is rc 2 (no skip)" 2 env PARSE5_DIR="$P5" "$S" "$T/nodrv"

# D-0238/D-0275: official-board records the Cargo.lock parse5 rev, not the clone HEAD.
OB="$(cd "$(dirname "$0")" && pwd)/official-board.sh"
blk="$(sed -n '/^# >>> parse5-lock-rev/,/^# <<< parse5-lock-rev/p' "$OB")"
[ -n "$blk" ] || { echo "FAIL parse5-lock-rev block not found in official-board.sh"; fail=1; blk=':'; }
eval "$blk"
mkdir -p "$T/lock-rev"
ZEROS="$(printf '0%.0s' {1..40})"
plant_lock() {
  printf '# This file is automatically @generated by Cargo.\nversion = 4\n\n[[package]]\nname = "parse5"\nversion = "0.1.0"\nsource = "%s"\n' "$2" > "$1"
}
plant_lock "$T/lock-rev/Cargo.lock" "git+https://github.com/tariqrafique/parse5-rust?rev=${rev}#${rev}"
got="$(parse5_lock_rev "$T/lock-rev/Cargo.lock" || true)"
if [ "$got" = "$rev" ]; then echo "ok   parse5_lock_rev extracts lock rev"; else echo "FAIL parse5_lock_rev got '$got' want '$rev'"; fail=1; fi
check "require_parse5_lock_rev present 40-hex" 0 require_parse5_lock_rev "$T/lock-rev/Cargo.lock" "$P5"
plant_lock "$T/lock-rev/missing.lock" "registry+https://github.com/rust-lang/crates.io-index"
check "require_parse5_lock_rev missing git source" 2 require_parse5_lock_rev "$T/lock-rev/missing.lock" "$P5"
plant_lock "$T/lock-rev/short.lock" "git+https://github.com/tariqrafique/parse5-rust?rev=${rev:0:12}#${rev:0:12}"
check "require_parse5_lock_rev short rev is rc 2" 2 require_parse5_lock_rev "$T/lock-rev/short.lock" "$P5"
plant_lock "$T/lock-rev/absent.lock" "git+https://github.com/tariqrafique/parse5-rust?rev=${ZEROS}#${ZEROS}"
check "require_parse5_lock_rev rev absent from clone" 2 require_parse5_lock_rev "$T/lock-rev/absent.lock" "$P5"


plant_lock "$T/lock-rev/mismatch.lock" "git+https://github.com/tariqrafique/parse5-rust?rev=${rev}#${ZEROS}"
check "require_parse5_lock_rev halves differ says mismatch" 2 require_parse5_lock_rev "$T/lock-rev/mismatch.lock" "$P5"
if grep -q mismatch "$T/out"; then echo "ok   halves-differ message says mismatch"; else echo "FAIL halves-differ message: $(cat "$T/out")"; fail=1; fi

exit $fail
