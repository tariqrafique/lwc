// Generates crates/lwc-shared/src/errors/error_info.rs: the ONE port of the @lwc/errors error-info tables
// (AB-R003 / AB-0001), from the pinned oracle /workspace/lwc (b9e8007): packages/@lwc/errors, dist built.
//   node tools/gen-error-info/gen.mjs            write the file
//   node tools/gen-error-info/gen.mjs --stdout   print it (lwc-shared's freshness test compares)
import fs from 'fs'; import path from 'path'; import { createRequire } from 'module'; import { fileURLToPath } from 'url';
const errorsPkg = '/workspace/lwc/packages/@lwc/errors';
const req = createRequire(path.join(errorsPkg, '/'));
const E = req(errorsPkg);
const version = JSON.parse(fs.readFileSync(path.join(errorsPkg, 'package.json'), 'utf8')).version;
const LEVEL = Object.fromEntries(Object.entries(E.DiagnosticLevel).filter(([k]) => isNaN(+k)).map(([k, v]) => [v, k]));
const isInfo = (o) => o && typeof o === 'object' && typeof o.code === 'number' && 'message' in o;
const lit = (s) => JSON.stringify(s);
const lvl = (l) => `DiagnosticLevel::${LEVEL[l]}`;
const info = (o) => `LwcErrorInfo { code: ${o.code}, message: ${lit(o.message)}, level: ${lvl(o.level)}, url: ${o.url === undefined ? 'None' : `Some(${lit(o.url)})`}, strict_level: ${o.strictLevel === undefined ? 'None' : `Some(${lvl(o.strictLevel)})`} }`;
const groups = Object.entries(E).filter(([, v]) => v && typeof v === 'object' && !isInfo(v) && Object.values(v).some(isInfo)).sort(([a], [b]) => a.localeCompare(b));
const singles = Object.entries(E).filter(([, v]) => isInfo(v)).sort(([a], [b]) => a.localeCompare(b));
// Upstream source file of each group (error-info/{compiler,lwc-class,ssr,template-transform}.ts).
const srcDir = path.join(errorsPkg, 'src/compiler/error-info');
const fileOf = {};
for (const f of ['compiler', 'lwc-class', 'ssr', 'template-transform'])
  for (const m of fs.readFileSync(path.join(srcDir, `${f}.ts`), 'utf8').matchAll(/^export const (\w+) =/gm)) fileOf[m[1]] = f.replace('-', '_');
for (const [k] of [...groups, ...singles]) if (!fileOf[k]) throw new Error(`no upstream file for ${k}`);
const all = [];
let out = `//! GENERATED by tools/gen-error-info/gen.mjs from shipped @lwc/errors ${version}. Do not edit by hand.
//!
//! The one port of the \`@lwc/errors\` error-info tables (AB-R003 / AB-0001). Groups keep the upstream export
//! names (\`DecoratorErrors::ONE_WIRE_DECORATOR_ALLOWED\` is \`DecoratorErrors.ONE_WIRE_DECORATOR_ALLOWED\`).
#![allow(non_snake_case)]
use crate::{DiagnosticLevel, LwcErrorInfo};

/// Version of the \`@lwc/errors\` the table was generated from.
pub const SOURCE_VERSION: &str = ${lit(version)};
`;
for (const file of ['compiler', 'lwc_class', 'ssr', 'template_transform']) {
  out += `\n/// \`error-info/${file.replace('_', '-')}.ts\`.\npub mod ${file} {\n    use super::*;\n`;
  for (const [k, v] of singles.filter(([k]) => fileOf[k] === file)) { out += `\n    /// \`${k}\`.\n    pub const ${k}: LwcErrorInfo = ${info(v)};\n`; all.push([v.code, `${file}::${k}`]); }
  for (const [g, obj] of groups.filter(([g]) => fileOf[g] === file)) {
    out += `\n    /// \`${g}\`.\n    pub mod ${g} {\n        use super::*;\n`;
    for (const [k, v] of Object.entries(obj)) { if (!isInfo(v)) continue; out += `        pub const ${k}: LwcErrorInfo = ${info(v)};\n`; all.push([v.code, `${file}::${g}::${k}`]); }
    out += `    }\n`;
  }
  out += `}\npub use ${file}::*;\n`;
}
all.sort((a, b) => a[0] - b[0]);
for (let i = 1; i < all.length; i++) if (all[i][0] === all[i - 1][0]) throw new Error(`duplicate code ${all[i][0]}`);
out += `\n/// Every entry, sorted by code (${all.length} entries).\npub static ALL: &[LwcErrorInfo] = &[\n${all.map(([, n]) => `    ${n},`).join('\n')}\n];\n`;
if (process.argv.includes('--stdout')) process.stdout.write(out);
else { const here = path.dirname(fileURLToPath(import.meta.url)); fs.writeFileSync(path.join(here, '../../crates/lwc-shared/src/errors/error_info.rs'), out); console.log(all.length, 'infos'); }
