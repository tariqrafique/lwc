#!/usr/bin/env node
// JS <-> Rust differential corpus for LWC style compilation. See README.md.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { oracleRoot, styleCorpusRoot } from '../../harness/scripts/oracle-root.mjs';

const LWC = oracleRoot();
const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '../..');
const CAP = Number(process.env.STYLE_DIFF_CAP || 200);
const OUT = process.env.STYLE_DIFF_OUT || path.join(ROOT, 'target/style-diff');
const ALLOW = path.join(path.dirname(new URL(import.meta.url).pathname), 'allowlist.json');
const require = createRequire(import.meta.url);
const { transform } = require(path.join(LWC, 'packages/@lwc/style-compiler/dist/index.cjs'));

// ---- corpus
function walk(d, acc = []) {
  if (!fs.existsSync(d)) return acc;
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    if (e.name === 'node_modules' || e.name === 'dist') continue;
    const p = path.join(d, e.name);
    if (e.isDirectory()) walk(p, acc); else if (e.name.endsWith('.css')) acc.push(p);
  }
  return acc;
}
const seen = new Set();
const corpus = [];
const add = (p, kind) => {
  const src = fs.readFileSync(p, 'utf8');
  const h = crypto.createHash('sha256').update(src).digest('hex');
  if (seen.has(h)) return false;
  seen.add(h); corpus.push({ path: path.relative(LWC, p), abs: p, src, kind }); return true;
};
const MODE = process.env.STYLE_DIFF_CORPUS || 'all'; // integration | slds | all
const SLDS_ROOT = styleCorpusRoot();
const SLDS_CAP = Number(process.env.STYLE_DIFF_SLDS_CAP || 300);
let real = 0;
if (MODE !== 'slds') for (const pkg of ['integration-wtr', 'integration-wdio', 'integration-types']) {
  for (const p of walk(path.join(LWC, 'packages/@lwc', pkg)).sort()) {
    if (real >= CAP) break;
    if (add(p, 'real')) real++;
  }
}
if (MODE !== 'integration') {
  // SLDS / lightning-base-components: dedup by hash, prioritize @supports > @media > var( > rest.
  const all = [];
  const walkAll = (d) => { if (!fs.existsSync(d)) return; for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name); if (e.isDirectory()) { if (e.name !== 'node_modules' && e.name !== '.git') walkAll(p); } else if (e.name.endsWith('.css')) all.push(p); } };
  for (const sub of ['lbc', 'slds', 'lbc-recipes']) walkAll(path.join(SLDS_ROOT, sub));
  const rank = (src) => (src.includes('@supports') ? 0 : src.includes('@media') ? 1 : src.includes('var(') ? 2 : 3);
  const items = all.sort().map((p) => { const src = fs.readFileSync(p, 'utf8'); return { p, r: rank(src) }; }).sort((a, b) => a.r - b.r);
  let n = 0;
  for (const { p } of items) { if (n >= SLDS_CAP) break; if (add(p, 'slds')) n++; }
}
if (MODE !== 'slds' && !process.env.STYLE_DIFF_NO_FIXTURES) {
  const fx = path.join(LWC, 'packages/@lwc/style-compiler/src/__tests__/fixtures');
  for (const d of fs.readdirSync(fx).sort()) { const p = path.join(fx, d, 'actual.css'); if (fs.existsSync(p)) add(p, 'fixture-smoke'); }
}

if (!process.env.STYLE_DIFF_NO_PARSE_ERRORS) {
  // PostCSS parse-error inputs (unclosed block/bracket/string/comment, unknown word, ...), generated by
  // gen-parse-errors.mjs. No real corpus file has a parse error, so these are the only coverage of that path.
  const pe = path.join(ROOT, 'crates/lwc-style/tests/parse-errors');
  if (fs.existsSync(pe)) for (const d of fs.readdirSync(pe).sort()) { const p = path.join(pe, d, 'actual.css'); if (fs.existsSync(p)) add(p, 'parse-error'); }
}

// ---- jobs
const CONFIGS = [
  ['default', {}], ['scoped', { scoped: true }], ['dss', { dss: true }],
  ['scoped+dss', { scoped: true, dss: true }], ['erm', { erm: true }], ['erm+scoped', { erm: true, scoped: true }],
];
const jobs = [];
for (const f of corpus) {
  const forced = f.abs.endsWith('.scoped.css');
  const keys = new Set();
  for (const [name, c] of CONFIGS) {
    const cfg = { scoped: !!c.scoped || forced, dss: !!c.dss, erm: !!c.erm };
    const k = JSON.stringify(cfg); if (keys.has(k)) continue; keys.add(k);
    jobs.push({ id: jobs.length, file: f, config: name + (forced && !c.scoped ? '(forced scoped)' : ''), cfg });
  }
}

// ---- JS side
const normVer = (s) => s.replace(/LWC compiler v[^*]*\*\//g, 'LWC compiler vX.X.X*/');
function jsErr(err) {
  if (err instanceof AggregateError) return err.errors.map(({ name, reason, column, line }) => ({ name, reason, column, line }));
  if (err.name === 'CssSyntaxError') return { name: err.name, reason: err.reason, column: err.column, line: err.line };
  return { name: err.name, message: err.message };
}
for (const j of jobs) {
  try {
    j.js = { ok: true, code: transform(j.file.src, j.file.abs, { scoped: j.cfg.scoped, disableSyntheticShadowSupport: j.cfg.dss, experimentalErrorRecoveryMode: j.cfg.erm }).code };
  } catch (e) { j.js = { ok: false, err: jsErr(e) }; }
}

// ---- Rust side
const bin = path.join(ROOT, 'target/release/examples/style_diff');
if (!process.env.STYLE_DIFF_NO_BUILD) execFileSync('cargo', ['build', '-q', '--release', '-p', 'lwc-style', '--example', 'style_diff'], { cwd: ROOT, stdio: 'inherit' });
const input = jobs.map((j) => JSON.stringify({ id: j.id, src: j.file.src, filename: j.file.abs, ...j.cfg })).join('\n') + '\n';
const rsOut = execFileSync(bin, { input, maxBuffer: 1 << 30 }).toString().trim().split('\n').map((l) => JSON.parse(l));
for (const r of rsOut) jobs[r.id].rs = r;

// ---- semantic fallback: eval stylesheet(token, host, dir) for 4 combos
function evalModule(code) {
  let body = code.replace(/import\s+(\w+)\s+from\s+("[^"]*"|'[^']*');?/g, 'const $1 = [];');
  body = body.replace(/export default /g, 'return ');
  const arr = new Function(body)();
  if (!arr) return 'undefined';
  const fns = arr.filter((x) => typeof x === 'function');
  const out = [];
  for (const host of [false, true]) for (const dir of [false, true])
    out.push(fns.map((f) => String(f('x-tok', host, dir))).join('|'));
  return JSON.stringify([arr.length, out]);
}

// ---- compare
const allow = fs.existsSync(ALLOW) ? JSON.parse(fs.readFileSync(ALLOW, 'utf8')) : [];
const res = { pass: 0, passErr: 0, semantic: 0, fail: 0, allowed: 0, skip: 0 };
const fails = [];
const canon = (v) => JSON.stringify(v, (k, x) => (x && typeof x === 'object' && !Array.isArray(x) ? Object.fromEntries(Object.entries(x).sort()) : x));
const firstDiff = (a, b) => { let i = 0; while (i < a.length && a[i] === b[i]) i++; return { at: i, js: a.slice(Math.max(0, i - 40), i + 60), rs: b.slice(Math.max(0, i - 40), i + 60) }; };
for (const j of jobs) {
  const { js, rs } = j; let status, detail;
  if (!rs) { res.skip++; continue; }
  if (rs.panic) { status = 'fail'; detail = { category: 'rust-panic' }; }
  else if (js.ok && rs.ok) {
    const a = normVer(js.code), b = normVer(rs.code);
    if (a === b) status = 'pass';
    else {
      let sem = 'n/a';
      try { sem = evalModule(a) === evalModule(b) ? 'equal' : 'different'; } catch (e) { sem = 'eval-error: ' + e.message; }
      status = 'fail'; detail = { category: 'byte-mismatch', semantic: sem, diff: firstDiff(a, b) };
    }
  } else if (!js.ok && !rs.ok) {
    if (canon(js.err) === canon(rs.err)) status = 'passErr';
    else { status = 'fail'; detail = { category: 'error-mismatch', js: js.err, rs: rs.err }; }
  } else { status = 'fail'; detail = { category: js.ok ? 'rust-err-js-ok' : 'js-err-rust-ok', js: js.ok ? undefined : js.err, rs: rs.ok ? undefined : rs.err }; }
  if (status === 'fail' && allow.some((a) => a.file === j.file.path && (!a.config || a.config === j.config))) { res.allowed++; continue; }
  res[status]++;
  if (status === 'fail') fails.push({ file: j.file.path, kind: j.file.kind, config: j.config, ...detail });
}
fs.mkdirSync(OUT, { recursive: true });
const summary = { files: corpus.length, realFiles: corpus.filter((f) => f.kind === 'real').length, fixtureSmoke: corpus.filter((f) => f.kind === 'fixture-smoke').length, parseErrorFiles: corpus.filter((f) => f.kind === 'parse-error').length, sldsFiles: corpus.filter((f) => f.kind === 'slds').length,
  coverage: Object.fromEntries(['@media', 'var(', '@supports'].map((t) => [t, Object.fromEntries(['real', 'slds'].map((k) => [k, corpus.filter((f) => f.kind === k && f.src.includes(t)).length]))])), jobs: jobs.length, ...res };
const errReasons = {}; for (const j of jobs) if (!j.js.ok && j.file.kind === "slds") { const e = Array.isArray(j.js.err) ? j.js.err[0] : j.js.err; const k = (e.reason || e.message || "").slice(0, 60); errReasons[k] = (errReasons[k] || 0) + 1; }
const sources = { lbc: 0, slds: 0, "lbc-recipes": 0 }; for (const f of corpus) if (f.kind === "slds") sources[path.relative(SLDS_ROOT, f.abs).split(path.sep)[0]]++;
fs.writeFileSync(path.join(OUT, "report.json"), JSON.stringify({ summary, sources, errReasons, fails }, null, 2));
console.log(JSON.stringify(summary));
for (const f of fails.slice(0, 50)) console.log('FAIL', f.config, f.file, f.category, f.semantic || '');
if (fails.length) { console.log(`${fails.length} failures; full report: ${path.join(OUT, 'report.json')}`); process.exit(1); }
console.log('100% MATCH');
