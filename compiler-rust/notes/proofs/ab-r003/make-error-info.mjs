// Generates crates/lwc-shared/src/error_info.rs (AB-R003: the ONE error-info + url table) from shipped
// 9.5.3 @lwc/errors. Usage: node make-error-info.mjs <worktree>
import fs from 'fs'; import { createRequire } from 'module';
const E = createRequire('/workspace/oracle953/')('@lwc/errors');
const LEVEL = Object.fromEntries(Object.entries(E.DiagnosticLevel).filter(([k]) => isNaN(+k)).map(([k, v]) => [v, k]));
const byCode = new Map(); const names = new Map();
const walk = (o, path, d) => { if (!o || typeof o !== 'object' || d > 3) return;
  if (typeof o.code === 'number' && 'message' in o) {
    const prev = byCode.get(o.code);
    if (prev && JSON.stringify(prev) !== JSON.stringify(o)) throw new Error(`conflicting info ${o.code}`);
    byCode.set(o.code, o); (names.get(o.code) ?? names.set(o.code, new Set()).get(o.code)).add(path.at(-1)); return; }
  for (const [k, v] of Object.entries(o)) walk(v, [...path, k], d + 1); };
walk(E, [], 0);
const lit = (s) => JSON.stringify(s);
const lvl = (l) => `DiagnosticLevel::${LEVEL[l]}`;
const url = (u) => u === undefined ? 'None' : `Some(${lit(u)})`;
const info = (o) => `LwcErrorInfo { code: ${o.code}, message: ${lit(o.message)}, level: ${lvl(o.level)}, url: ${url(o.url)}, strict_level: ${o.strictLevel === undefined ? 'None' : `Some(${lvl(o.strictLevel)})`} }`;
const codes = [...byCode.keys()].sort((a, b) => a - b);
const named = ['NO_AVAILABLE_TRANSFORMER', 'JS_TRANSFORMER_ERROR', 'HTML_TRANSFORMER_ERROR', 'CSS_TRANSFORMER_ERROR', 'JS_TRANSFORMER_DECORATOR_ERROR'];
const T = E.TransformerErrors;
const rs = `//! GENERATED by notes/lwc-rust-migrate/proofs/ab-r003/make-error-info.mjs from shipped 9.5.3
//! \`@lwc/errors\` (${codes.length} error infos). Do not edit by hand.
//!
//! AB-R003: the one error-info table. Every \`url\` / \`level\` the compiler seam reports is read here.
use crate::{DiagnosticLevel, LwcErrorInfo};

${named.map((n) => `/// \`TransformerErrors.${n}\`.\npub const ${n}: LwcErrorInfo = ${info(T[n])};`).join('\n')}

/// Every shipped info, sorted by code.
pub static ERROR_INFO: &[LwcErrorInfo] = &[
${codes.map((c) => `    ${info(byCode.get(c))}, // ${[...names.get(c)].join(', ')}`).join('\n')}
];
`;
fs.writeFileSync(`${process.argv[2]}/crates/lwc-shared/src/error_info.rs`, rs);
console.log(codes.length, 'infos');
