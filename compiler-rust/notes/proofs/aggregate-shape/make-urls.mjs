// Generates crates/lwc-compiler-napi/src/error_urls.rs from shipped 9.5.3 @lwc/errors info tables.
import fs from 'fs'; import { createRequire } from 'module';
const E = createRequire('/workspace/oracle953/')('@lwc/errors');
const m = new Map();
const walk = (o, d) => { if (!o || typeof o !== 'object' || d > 3) return;
  if (typeof o.code === 'number' && 'message' in o) { m.set(o.code, o.url ?? ''); return; }
  for (const v of Object.values(o)) walk(v, d + 1); };
walk(E, 0);
const withUrl = [...m].filter(([, u]) => u).sort((a, b) => a[0] - b[0]);
for (const [c, u] of withUrl) if (u !== `https://lwc.dev/guide/error_codes#lwc${c}`) throw new Error(`non-canonical url ${c}`);
const rs = `//! GENERATED by notes/lwc-rust-migrate/proofs/aggregate-shape/make-urls.mjs from shipped 9.5.3
//! \`@lwc/errors\` (${m.size} error infos). Codes whose info has a non-empty \`url\`; every such url is
//! \`https://lwc.dev/guide/error_codes#lwc{code}\`. All other codes have \`url: ''\`.
pub const CODES_WITH_URL: &[u32] = &[${withUrl.map(([c]) => c).join(', ')}];

/// \`errorInfo.url\` for \`code\` (shipped \`CompilerError.from(diagnostic)\` copies it onto each entry).
pub fn error_url(code: Option<u32>) -> String {
    match code {
        Some(c) if CODES_WITH_URL.binary_search(&c).is_ok() => format!("https://lwc.dev/guide/error_codes#lwc{c}"),
        _ => String::new(),
    }
}
`;
fs.writeFileSync('/workspace/lwc-compiler-rust/crates/lwc-compiler-napi/src/error_urls.rs', rs);
console.log(withUrl.length, 'of', m.size);
